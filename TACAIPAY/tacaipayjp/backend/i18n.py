def load_i18n(lang: str) -> dict[str, str]:
    """Load translations for given language from JSON files.

    Merges DEFAULT_LANG (ja) first as fallback, then requested language on top.
    If JSON files are not available, falls back to in-memory TRANSLATIONS dict.
    """
    messages: dict[str, str] = {}
    loaded_any = False
    for candidate in (DEFAULT_LANG, lang):
        path = I18N_DIR / f"{candidate}.json"
        if not path.exists():
            continue
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, dict):
                messages.update({str(k): str(v) for k, v in data.items()})
                loaded_any = True
        except (json.JSONDecodeError, IOError):
            pass
    if not loaded_any:
        # Fallback to in-memory TRANSLATIONS dict
        messages = dict(TRANSLATIONS.get(DEFAULT_LANG, {}))
        messages.update(TRANSLATIONS.get(lang, {}))
    return messages


def t(lang_or_messages, key: str, default: str = None, **kwargs) -> str:
    """Translate a key to the given language or messages dict.

    Supports two calling patterns:
      1. t(messages_dict, key, default=None) — new pattern using load_i18n() result
      2. t(lang_string, key) — legacy pattern using in-memory TRANSLATIONS

    If default is provided and key is not found, default is returned instead of key.
    """
    if isinstance(lang_or_messages, dict):
        # New pattern: dict from load_i18n()
        text = lang_or_messages.get(key, default if default is not None else key)
    else:
        # Legacy pattern: language code string
        lang = lang_or_messages
        if lang not in SUPPORTED_LANGS:
            lang = DEFAULT_LANG
        text = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANG]).get(key, default if default is not None else key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except KeyError:
            return text
    return text


def get_lang(request) -> str:
    """Extract language from query param or cookie."""
    lang = request.query_params.get("lang", "")
    if lang in SUPPORTED_LANGS:
        return lang
    cookie = request.cookies.get("tacai_portal_lang", "")
    if cookie in SUPPORTED_LANGS:
        return cookie
    return DEFAULT_LANG
